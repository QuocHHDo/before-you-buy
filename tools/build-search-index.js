// Builds data/search-index.js from every guide's data file. Run: node tools/build-search-index.js
// tests/search.test.js fails if the committed index is out of date.
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");

function build() {
  global.window = {};
  require(path.join(root, "data/catalog.js"));
  const items = global.window.BYB_CATALOG.groups.flatMap((g) => g.items);
  const out = [];
  for (const it of items) {
    const file = fs.readdirSync(path.join(root, "data")).filter((f) => f.endsWith(".js") && !["catalog.js", "search-index.js", "icons.js"].includes(f))
      .find((f) => {
        global.window = {};
        delete require.cache[require.resolve(path.join(root, "data", f))];
        require(path.join(root, "data", f));
        return global.window.SITE_DATA && global.window.SITE_DATA.category === it.id;
      });
    if (!file) throw new Error("no data file for " + it.id);
    global.window = {};
    delete require.cache[require.resolve(path.join(root, "data", file))];
    require(path.join(root, "data", file));
    const D = global.window.SITE_DATA;
    const base = it.href === "./" ? "./" : it.href;
    D.traps.forEach((t) => out.push({ g: it.id, k: "trap", h: t.claim.replace(/\\?"/g, "").replace(/"/g, ""), x: t.reality, u: base + "#traps" }));
    D.questions.forEach((q) => out.push({ g: it.id, k: "question", h: q.ask, x: q.why, u: base + "#tool" }));
    D.picks.forEach((p) => out.push({ g: it.id, k: "pick", h: p.name, x: p.why, u: base + "#picks" }));
  }
  return out;
}

function render(entries) {
  return "// Generated by tools/build-search-index.js. Do not edit by hand.\nwindow.BYB_INDEX = " + JSON.stringify(entries) + ";\n";
}

if (require.main === module) {
  const e = build();
  fs.writeFileSync(path.join(root, "data/search-index.js"), render(e));
  console.log("wrote " + e.length + " entries");
}
module.exports = { build, render };
